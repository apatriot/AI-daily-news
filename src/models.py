"""AI Daily — data models."""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime


@dataclass
class RawItem:
    title: str
    url: str
    source_id: str
    source_name: str
    category: str
    published: datetime
    summary_raw: str = ""
    weight: float = 0.5


@dataclass
class Story:
    id: str
    title: str
    url: str
    source_id: str
    source_name: str
    category: str
    published: datetime
    summary_raw: str
    cluster: str = "industry"
    subtopic: str = ""
    tags: list[str] = field(default_factory=list)
    related: list[dict] = field(default_factory=list)

    # generated by LLM (or fallback)
    title_zh: str = ""
    summary_zh: str = ""
    key_points: list[str] = field(default_factory=list)
    why_matters: str = ""
    why_for_you: str = ""
    read_min: int = 1

    # ranking
    section: str = ""
    scores: dict[str, float] = field(default_factory=dict)

    def to_public(self) -> dict:
        """Serializable payload for templates / archive."""
        return {
            "id": self.id,
            "title": self.title_zh or self.title,
            "title_original": self.title,
            "url": self.url,
            "source": self.source_name,
            "source_id": self.source_id,
            "published": self.published.isoformat(),
            "summary": self.summary_zh,
            "key_points": self.key_points,
            "why_matters": self.why_matters,
            "why_for_you": self.why_for_you,
            "tags": self.tags,
            "cluster": self.cluster,
            "subtopic": self.subtopic,
            "related": self.related,
            "read_min": self.read_min,
            "scores": self.scores,
            "section": self.section,
        }
